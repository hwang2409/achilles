import type { ErrorRow, ModelRow, Page, ModelSeriesPoint, SeriesRow, ToolRow } from "./telemetry-types";
import type { Window } from "./telemetry-client";

export type AggregateTab = "models" | "tools" | "errors";
export const modelKey = (row: ModelRow) => JSON.stringify([row.provider, row.model]);
export const toolKey = (row: ToolRow) => JSON.stringify([row.tool_name, row.tool_type]);
export const errorKey = (row: ErrorRow) => `${row.trace_id}:${row.span_id}`;

/** Adjacent cursor reads can overlap if a row's sort rank changes. Keep its first position and newest values. */
export function mergePage<T>(prefix: readonly T[], page: Page<T>, key: (row: T) => string): Page<T> {
  const items = new Map(prefix.map((row) => [key(row), row]));
  for (const row of page.items) items.set(key(row), row);
  return { ...page, items: [...items.values()] };
}

/** Zeta sends only occupied UTC buckets and only the top model keys. Leave unrepresented keys absent. */
export function modelTrends(rows: SeriesRow[], window: Window, bucket: "hour" | "day") {
  const groups = new Map<string, Map<number, ModelSeriesPoint>>();
  for (const { key, point: { errors, ...point } } of rows) {
    if (key === null) continue;
    // Normalize JSON escapes as well as whitespace (the key is generated by zeta, not a display name).
    const canonical = JSON.stringify(JSON.parse(key));
    if (!groups.has(canonical)) groups.set(canonical, new Map());
    // group_by: "model" admits only calls for this provider/model key.
    groups.get(canonical)!.set(point.start_ns, { ...point, errored_model_calls: errors });
  }
  const step = (bucket === "hour" ? 1 : 24) * 3.6e12;
  return new Map([...groups].map(([key, points]) => {
    const series: ModelSeriesPoint[] = [];
    for (let start = Math.floor(window.start_ns / step) * step; start < window.end_ns; start += step) {
      series.push(points.get(start) ?? {
        start_ns: start, end_ns: start + step, sessions: 0, traces: 0, spans: 0, errored_model_calls: 0,
        model_calls: 0, tool_calls: 0, input_tokens: 0, output_tokens: 0, total_tokens: 0, duration_ns: 0,
      });
    }
    return [key, series];
  }));
}
